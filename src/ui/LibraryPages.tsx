import { Alert, Button, Form, Tab, Tabs } from 'react-bootstrap'
import { SOURCES, type Problem, type Source, type Topic } from '@/content/schema'
import type { LibraryEntry } from '@/core/library'
import { applicableFilter, filterEntries, type ProblemFilter } from '@/core/problems'
import { CodeBlock } from './CodeBlock'
import { Filters } from './Filters'
import { Link } from './Link'
import { ConceptTags } from './progress'
import type { Route } from './route'
import { Statement } from './Statement'

const SOURCE_LABEL: Record<Source, string> = {
  'built-in': 'Built-in',
  user: 'Added by you',
  ai: 'Generated by AI',
}

interface LibraryProps {
  entries: LibraryEntry[]
  filter: ProblemFilter
  disabled: boolean
  onFilter: (filter: ProblemFilter, disabled: boolean) => void
}

export function LibraryPage({ entries: all, filter: asked, disabled, onFilter }: LibraryProps) {
  const listed = (withDisabled: boolean) =>
    withDisabled ? all : all.filter((e) => e.topic.enabled)
  const entries = listed(disabled)
  const filter = applicableFilter(asked, entries, [])
  const shown = filterEntries(entries, filter)
  const filtered = Object.values(filter).some(Boolean)
  const sources = SOURCES.filter((s) => entries.some((e) => e.source === s)).map((value) => ({
    value,
    label: SOURCE_LABEL[value],
  }))

  return (
    <section aria-labelledby="library-title" className="d-grid gap-3">
      <h1 id="library-title" className="h3 mb-0">
        Coding problems
      </h1>
      {all.length === 0 ? (
        <div className="ws-panel ws-empty">
          <h2 className="h5 mb-0">No problems yet</h2>
          <p className="text-body-secondary">Problems are added to a topic.</p>
          <Link className="btn btn-primary" to={{ page: 'topics' }}>
            Open Topics
          </Link>
        </div>
      ) : (
        <>
          <Filters
            entries={entries}
            sources={sources}
            filter={filter}
            onFilter={(f) => onFilter(applicableFilter(f, entries, []), disabled)}
          >
            <p className="ws-count" aria-live="polite">
              {filtered
                ? `${shown.length} of ${entries.length} problems`
                : `${entries.length} problems`}
            </p>
            <Form.Check
              type="switch"
              role="switch"
              id="library-disabled"
              label="Show disabled topics"
              checked={disabled}
              onChange={({ target: { checked } }) =>
                onFilter(applicableFilter(filter, listed(checked), []), checked)
              }
            />
            <Button
              variant="link"
              className="ms-auto"
              disabled={!filtered}
              onClick={() => onFilter({}, disabled)}
            >
              Clear filters
            </Button>
          </Filters>
          <section className="ws-panel" aria-label="Problems">
            {shown.length === 0 ? (
              <div className="ws-empty">
                {entries.length === 0 ? (
                  <>
                    <h2 className="h5 mb-0">Every problem is in a disabled topic</h2>
                    <p className="text-body-secondary">Show disabled topics to see them.</p>
                  </>
                ) : (
                  <>
                    <h2 className="h5 mb-0">No problems match these filters</h2>
                    <p className="text-body-secondary">Widen the search or clear the filters.</p>
                  </>
                )}
              </div>
            ) : (
              <ul className="ws-problems">
                {shown.map((e) => (
                  <LibraryRow key={`${e.topic.id}/${e.id}`} entry={e} />
                ))}
              </ul>
            )}
          </section>
        </>
      )}
    </section>
  )
}

function LibraryRow({ entry }: { entry: LibraryEntry }) {
  const { topic, id, title, concepts, difficulty, source, errors } = entry
  return (
    <li className="ws-problem ws-library-problem" aria-label={title}>
      <div className="ws-problem-name">
        <Link to={{ page: 'library-problem', topic: topic.id, problem: id }}>{title}</Link>
        <div className="ws-problem-meta">
          <span>
            {topic.name}
            {!topic.enabled && ' (disabled)'}
          </span>
          <ConceptTags names={concepts.map((c) => c.name)} />
        </div>
        {errors.length > 0 && <p className="ws-problem-errors">Not served: {errors.join('; ')}</p>}
      </div>
      <span className="ws-difficulty" data-level={difficulty}>
        {difficulty}
      </span>
      <span className="ws-source">{source && SOURCE_LABEL[source]}</span>
    </li>
  )
}

interface ProblemProps {
  entry: LibraryEntry
  back: Route
  onTry: (topic: Topic, problem: Problem) => void
  onDelete: () => void
}

export function LibraryProblem({ entry, back, onTry, onDelete }: ProblemProps) {
  const { topic, problem, title, errors } = entry
  const remove = () => {
    if (confirm(`Delete "${title}"? Its past attempts will be kept.`)) onDelete()
  }
  return (
    <section aria-label={title} className="ws-report-page">
      <div className="d-flex flex-wrap gap-2">
        <Link className="btn btn-outline-secondary" to={back}>
          Back to coding problems
        </Link>
        <div className="d-flex gap-2 ms-auto">
          {problem && topic.enabled && (
            <Button onClick={() => onTry(topic, problem)}>Try it</Button>
          )}
          <Button variant="outline-danger" onClick={remove}>
            Delete
          </Button>
        </div>
      </div>
      {problem ? (
        <Served topic={topic} problem={problem} />
      ) : (
        <Broken entry={entry} errors={errors} />
      )}
    </section>
  )
}

function Served({ topic, problem }: { topic: Topic; problem: Problem }) {
  const { wordings } = problem
  const visible = problem.visible_tests.join(', ')
  return (
    <>
      <div className="ws-panel">
        {wordings.length === 1 ? (
          <Statement topic={topic} problem={problem} wording={wordings[0]} />
        ) : (
          <Tabs defaultActiveKey={0} className="ws-wordings px-3 pt-3">
            {wordings.map((wording, i) => (
              <Tab key={i} eventKey={i} title={`Wording ${i + 1}`}>
                <Statement topic={topic} problem={problem} wording={wording} />
              </Tab>
            ))}
          </Tabs>
        )}
      </div>
      <section className="ws-panel ws-attempt-part" aria-label="Starter code">
        <h2 className="h5">Starter code</h2>
        <CodeBlock value={problem.starter_code} language="python" label="Starter code" />
      </section>
      <section className="ws-panel ws-attempt-part" aria-label="Hints">
        <h2 className="h5">Hints</h2>
        <ol className="mb-0">
          {problem.hints.map((hint, i) => (
            <li key={i}>{hint}</li>
          ))}
        </ol>
      </section>
      <section className="ws-panel ws-attempt-part" aria-label="Reference solution">
        <h2 className="h5">Reference solution</h2>
        <CodeBlock
          value={problem.reference_solution}
          language="python"
          label="Reference solution"
        />
      </section>
      <section className="ws-panel ws-attempt-part" aria-label="Tests">
        <h2 className="h5">Tests</h2>
        <p className="text-body-secondary">The solver sees only {visible}; the rest are hidden.</p>
        <CodeBlock value={problem.tests} language="python" label="Tests" />
      </section>
    </>
  )
}

function Broken({ entry, errors }: { entry: LibraryEntry; errors: string[] }) {
  return (
    <>
      <div className="ws-panel ws-attempt-part">
        <h1 className="h3">{entry.title}</h1>
        <p className="text-body-secondary">{entry.topic.name}</p>
        <Alert variant="warning" className="mb-0">
          This problem is not served: it breaks the current content rules.
          <ul className="mb-0 mt-2">
            {errors.map((e) => (
              <li key={e}>{e}</li>
            ))}
          </ul>
        </Alert>
      </div>
      <section className="ws-panel ws-attempt-part" aria-label="Stored problem">
        <h2 className="h5">Stored problem</h2>
        <CodeBlock
          value={JSON.stringify(entry.raw, null, 2)}
          language="json"
          label="Stored problem"
        />
      </section>
    </>
  )
}
