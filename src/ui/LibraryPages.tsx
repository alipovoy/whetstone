import type { ReactNode } from 'react'
import { Alert, Button, Form, Tab, Tabs } from 'react-bootstrap'
import {
  conceptNames,
  QUESTION_TYPES,
  SOURCES,
  type Problem,
  type Question,
  type Source,
  type Topic,
} from '@/content/schema'
import type { LibraryEntry } from '@/core/library'
import { applicableFilter, filterEntries, type ItemFilter } from '@/core/problems'
import type { ItemList } from '@/core/topics'
import { CodeBlock } from './CodeBlock'
import { Filters } from './Filters'
import { capital, plural } from './format'
import { Link } from './Link'
import { Markdown } from './Markdown'
import { ConceptTags, TYPE_LABEL } from './progress'
import { addItemsFor, type Route } from './route'
import { Statement } from './Statement'

const SOURCE_LABEL: Record<Source, string> = {
  'built-in': 'Built-in',
  user: 'Added by you',
  ai: 'Generated by AI',
}

const LIST_TITLE: Record<ItemList, string> = {
  problems: 'Coding problems',
  questions: 'Quiz questions',
}

export const NOUN: Record<ItemList, string> = { problems: 'problem', questions: 'question' }

interface LibraryProps {
  list: ItemList
  entries: LibraryEntry[]
  filter: ItemFilter
  disabled: boolean
  // Said once after items are added.
  notice?: string
  onDismiss: () => void
  onFilter: (filter: ItemFilter, disabled: boolean) => void
}

export function LibraryPage({
  list,
  entries: all,
  filter: asked,
  disabled,
  notice,
  onDismiss,
  onFilter,
}: LibraryProps) {
  const noun = NOUN[list]
  const listed = (withDisabled: boolean) =>
    withDisabled ? all : all.filter((e) => e.topic.enabled)
  const entries = listed(disabled)
  const filter = applicableFilter(asked, entries, [])
  const shown = filterEntries(entries, filter)
  const filtered = Object.values(filter).some(Boolean)
  const sources = SOURCES.filter((s) => entries.some((e) => e.source === s)).map((value) => ({
    value,
    label: SOURCE_LABEL[value],
  }))
  const types =
    list === 'questions'
      ? QUESTION_TYPES.map((value) => ({ value, label: TYPE_LABEL[value] }))
      : undefined

  return (
    <section aria-labelledby="library-title" className="d-grid gap-3">
      <div className="d-flex flex-wrap align-items-center gap-2">
        <h1 id="library-title" className="h3 mb-0 me-auto">
          {LIST_TITLE[list]}
        </h1>
        <Link className="btn btn-primary" to={addItemsFor(list, filter, entries)}>
          Add {noun}s
        </Link>
      </div>
      {notice && (
        <Alert variant="success" dismissible onClose={onDismiss} className="mb-0">
          {notice}
        </Alert>
      )}
      {all.length === 0 ? (
        <div className="ws-panel ws-empty">
          <h2 className="h5 mb-0">No {noun}s yet</h2>
          <p className="text-body-secondary">Add {noun}s to a topic.</p>
        </div>
      ) : (
        <>
          <Filters
            entries={entries}
            sources={sources}
            types={types}
            filter={filter}
            onFilter={(f) => onFilter(applicableFilter(f, entries, []), disabled)}
          >
            <p className="ws-count" aria-live="polite">
              {filtered
                ? `${shown.length} of ${plural(entries.length, noun)}`
                : plural(entries.length, noun)}
            </p>
            <Form.Check
              type="switch"
              role="switch"
              id="library-disabled"
              label="Show disabled topics"
              checked={disabled}
              onChange={({ target: { checked } }) =>
                onFilter(applicableFilter(filter, listed(checked), []), checked)
              }
            />
            <Button
              variant="link"
              className="ms-auto"
              disabled={!filtered}
              onClick={() => onFilter({}, disabled)}
            >
              Clear filters
            </Button>
          </Filters>
          <section className="ws-panel" aria-label={capital(`${noun}s`)}>
            {shown.length === 0 ? (
              <div className="ws-empty">
                {entries.length === 0 ? (
                  <>
                    <h2 className="h5 mb-0">Every {noun} is in a disabled topic</h2>
                    <p className="text-body-secondary">Show disabled topics to see them.</p>
                  </>
                ) : (
                  <>
                    <h2 className="h5 mb-0">No {noun}s match these filters</h2>
                    <p className="text-body-secondary">Widen the search or clear the filters.</p>
                  </>
                )}
              </div>
            ) : (
              <ul className="ws-problems">
                {shown.map((e) => (
                  <LibraryRow key={`${e.topic.id}/${e.id}`} list={list} entry={e} />
                ))}
              </ul>
            )}
          </section>
        </>
      )}
    </section>
  )
}

function LibraryRow({ list, entry }: { list: ItemList; entry: LibraryEntry }) {
  const { topic, id, title, concepts, difficulty, type, source, errors } = entry
  return (
    <li className="ws-problem ws-library-item" data-list={list} aria-label={title}>
      <div className="ws-problem-name">
        <Link to={{ page: 'library-item', list, topic: topic.id, item: id }}>{title}</Link>
        <div className="ws-problem-meta">
          <span>
            {topic.name}
            {!topic.enabled && ' (disabled)'}
          </span>
          <ConceptTags names={concepts.map((c) => c.name)} />
        </div>
        {errors.length > 0 && <p className="ws-problem-errors">Not served: {errors.join('; ')}</p>}
      </div>
      {list === 'questions' && <span className="ws-source">{type && TYPE_LABEL[type]}</span>}
      <span className="ws-difficulty" data-level={difficulty}>
        {difficulty}
      </span>
      <span className="ws-source">{source && SOURCE_LABEL[source]}</span>
    </li>
  )
}

interface ItemProps<T> {
  entry: LibraryEntry<T>
  back: Route
  onDelete: () => void
}

export function LibraryProblem({
  entry,
  back,
  onTry,
  onDelete,
}: ItemProps<Problem> & { onTry: (topic: Topic, problem: Problem) => void }) {
  const { topic, item: problem } = entry
  return (
    <LibraryItem
      list="problems"
      entry={entry}
      back={back}
      confirmDelete="Its past attempts will be kept."
      onDelete={onDelete}
      actions={
        <>
          {problem && topic.enabled && (
            <Button onClick={() => onTry(topic, problem)}>Try it</Button>
          )}
          <Link
            className={`btn ${problem ? 'btn-outline-primary' : 'btn-primary'}`}
            to={{ page: 'edit-problem', topic: topic.id, problem: entry.id }}
          >
            Edit
          </Link>
        </>
      }
    >
      {problem && <ProblemView topic={topic} problem={problem} />}
    </LibraryItem>
  )
}

export function LibraryQuestion({ entry, back, onDelete }: ItemProps<Question>) {
  const { topic, item: question } = entry
  return (
    <LibraryItem list="questions" entry={entry} back={back} onDelete={onDelete}>
      {question && (
        <div className="ws-panel">
          <QuestionView topic={topic} question={question} />
        </div>
      )}
    </LibraryItem>
  )
}

interface LibraryItemProps {
  list: ItemList
  entry: LibraryEntry
  back: Route
  confirmDelete?: string
  onDelete: () => void
  actions?: ReactNode
  // The item as served; a broken one shows why it is not.
  children: ReactNode
}

function LibraryItem({
  list,
  entry,
  back,
  confirmDelete,
  onDelete,
  actions,
  children,
}: LibraryItemProps) {
  const remove = () => {
    if (confirm([`Delete "${entry.title}"?`, confirmDelete].filter(Boolean).join(' '))) onDelete()
  }
  return (
    <section aria-label={entry.title} className="ws-report-page">
      <div className="d-flex flex-wrap gap-2">
        <Link className="btn btn-outline-secondary" to={back}>
          Back to {LIST_TITLE[list].toLowerCase()}
        </Link>
        <div className="d-flex gap-2 ms-auto">
          {actions}
          <Button variant="outline-danger" onClick={remove}>
            Delete
          </Button>
        </div>
      </div>
      {entry.item ? children : <Broken list={list} entry={entry} />}
    </section>
  )
}

// The problem as stored: its wordings as the solver reads them, then what the solver does not see.
export function ProblemView({ topic, problem }: { topic: Topic; problem: Problem }) {
  const { wordings } = problem
  const visible = problem.visible_tests.join(', ')
  return (
    <>
      <div className="ws-panel">
        {wordings.length === 1 ? (
          <Statement topic={topic} problem={problem} wording={wordings[0]} />
        ) : (
          <Tabs defaultActiveKey={0} className="ws-wordings px-3 pt-3">
            {wordings.map((wording, i) => (
              <Tab key={i} eventKey={i} title={`Wording ${i + 1}`}>
                <Statement topic={topic} problem={problem} wording={wording} />
              </Tab>
            ))}
          </Tabs>
        )}
      </div>
      <section className="ws-panel ws-attempt-part" aria-label="Starter code">
        <h2 className="h5">Starter code</h2>
        <CodeBlock value={problem.starter_code} language="python" label="Starter code" />
      </section>
      <section className="ws-panel ws-attempt-part" aria-label="Hints">
        <h2 className="h5">Hints</h2>
        <ol className="mb-0">
          {problem.hints.map((hint, i) => (
            <li key={i}>{hint}</li>
          ))}
        </ol>
      </section>
      <section className="ws-panel ws-attempt-part" aria-label="Reference solution">
        <h2 className="h5">Reference solution</h2>
        <CodeBlock
          value={problem.reference_solution}
          language="python"
          label="Reference solution"
        />
      </section>
      <section className="ws-panel ws-attempt-part" aria-label="Tests">
        <h2 className="h5">Tests</h2>
        <p className="text-body-secondary">The solver sees only {visible}; the rest are hidden.</p>
        <CodeBlock value={problem.tests} language="python" label="Tests" />
      </section>
    </>
  )
}

interface QuestionViewProps {
  topic: Topic
  question: Question
  // A preview inside another page names the question below that page's title.
  preview?: boolean
}

// The question as stored: each wording with its options, the correct ones marked, then why.
export function QuestionView({ topic, question, preview }: QuestionViewProps) {
  const { wordings, answers } = question
  const Title = preview ? 'h3' : 'h1'
  const wording = ({ text, options }: Question['wordings'][number]) => (
    <>
      <Markdown source={text} />
      <ul className="ws-answer-options" aria-label="Options">
        {options.map((option, o) => {
          const correct = answers.includes(o)
          return (
            <li key={o} data-correct={correct || undefined}>
              <span>{option}</span>
              {correct && <span className="ws-tag ws-tag-correct">Correct</span>}
            </li>
          )
        })}
      </ul>
    </>
  )
  return (
    <div className="ws-statement">
      <Title className="h3">{question.summary}</Title>
      <p className="ws-statement-meta">
        <span className="ws-difficulty" data-level={question.difficulty}>
          {question.difficulty}
        </span>
        <span>{TYPE_LABEL[question.type]}</span>
        {topic.name}
      </p>
      <ConceptTags names={conceptNames(topic, question.concepts)} />
      {wordings.length === 1 ? (
        wording(wordings[0])
      ) : (
        <Tabs defaultActiveKey={0} className="mb-3">
          {wordings.map((w, i) => (
            <Tab key={i} eventKey={i} title={`Wording ${i + 1}`}>
              {wording(w)}
            </Tab>
          ))}
        </Tabs>
      )}
      <section className="ws-explanation" aria-label="Explanation">
        <h2 className="h6">Explanation</h2>
        <Markdown source={question.explanation} />
      </section>
    </div>
  )
}

function Broken({ list, entry }: { list: ItemList; entry: LibraryEntry }) {
  const noun = NOUN[list]
  return (
    <>
      <div className="ws-panel ws-attempt-part">
        <h1 className="h3">{entry.title}</h1>
        <p className="text-body-secondary">{entry.topic.name}</p>
        <Alert variant="warning" className="mb-0">
          This {noun} is not served: it breaks the current content rules.
          {list === 'problems' && ' Edit it to fix it.'}
          <ul className="mb-0 mt-2">
            {entry.errors.map((e) => (
              <li key={e}>{e}</li>
            ))}
          </ul>
        </Alert>
      </div>
      <section className="ws-panel ws-attempt-part" aria-label={`Stored ${noun}`}>
        <h2 className="h5">Stored {noun}</h2>
        <CodeBlock
          value={JSON.stringify(entry.raw, null, 2)}
          language="json"
          label={`Stored ${noun}`}
        />
      </section>
    </>
  )
}
